"""Render dashboard-style screenshots from the real analytics code.

    python -m tickerpulse.demo.screenshots --out docs/screenshots

Everything is computed by tickerpulse.analytics on SYNTHETIC data
(see tickerpulse/demo/synthetic.py); nothing is fetched from the network.
"""
from __future__ import annotations

import argparse
import warnings
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.dates as mdates
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch

from ..analytics.pipeline import analyze
from ..config import company_name
from .synthetic import generate

warnings.filterwarnings("ignore")

BG, PANEL, GRID = "#0f1419", "#171e27", "#26313d"
TXT, MUTED = "#e6edf3", "#8b98a5"
UP, DOWN, ACCENT, ACCENT2, WARN = "#2ecc8f", "#ff5c6c", "#4da3ff", "#b48cff", "#ffb84d"
FOOT = "DEMO DATA - synthetic prices and posts generated by tickerpulse.demo.synthetic"

plt.rcParams.update({
    "figure.facecolor": BG, "axes.facecolor": PANEL, "axes.edgecolor": GRID, "axes.labelcolor": MUTED,
    "xtick.color": MUTED, "ytick.color": MUTED, "text.color": TXT, "axes.titlecolor": TXT,
    "grid.color": GRID, "grid.linewidth": 0.6, "font.family": "DejaVu Sans", "font.size": 10,
    "axes.spines.top": False, "axes.spines.right": False,
})


def footer(fig, extra: str = ""):
    fig.text(0.012, 0.012, FOOT + (f"  |  {extra}" if extra else ""), color=MUTED, fontsize=8)


def header(fig, title: str, sub: str):
    fig.text(0.012, 0.965, title, fontsize=17, fontweight="bold", va="top")
    fig.text(0.012, 0.925, sub, fontsize=10, color=MUTED, va="top")


def style_dates(ax):
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %d"))
    ax.xaxis.set_major_locator(mdates.AutoDateLocator(minticks=3, maxticks=6))
    ax.grid(True, axis="y")


# ---------------------------------------------------------------- 1. architecture
def architecture(path: Path):
    fig, ax = plt.subplots(figsize=(15, 7.6))
    ax.set_xlim(0, 15); ax.set_ylim(0, 7.6); ax.axis("off")
    header(fig, "TickerPulse - architecture", "Multi-ticker real-time market & sentiment pipeline")

    def box(x, y, w, h, title, lines, color):
        ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.15",
                                    fc=PANEL, ec=color, lw=1.8))
        ax.text(x + w / 2, y + h - 0.32, title, ha="center", va="center", fontsize=11.5,
                fontweight="bold", color=color)
        for i, l in enumerate(lines):
            ax.text(x + w / 2, y + h - 0.78 - i * 0.36, l, ha="center", va="center", fontsize=9, color=TXT)

    def arrow(x1, y1, x2, y2, label=""):
        ax.add_patch(FancyArrowPatch((x1, y1), (x2, y2), arrowstyle="-|>", mutation_scale=16,
                                     color=MUTED, lw=1.6))
        if label:
            ax.text((x1 + x2) / 2, (y1 + y2) / 2 + 0.2, label, ha="center", fontsize=8, color=MUTED)

    srcs = [("Market prices", "yfinance 1-min bars"), ("Reddit", "r/stocks, r/investing, r/wsb"),
            ("StockTwits", "bullish/bearish tagged"), ("News", "company headlines")]
    for i, (t, s) in enumerate(srcs):
        y = 5.35 - i * 1.4
        box(0.2, y, 2.9, 1.0, t, [s], ACCENT)
        arrow(3.1, y + 0.5, 4.4, 3.8 if i in (1, 2) else (3.8 + (0.6 if i == 0 else -0.6)))
    box(4.4, 2.4, 2.7, 2.8, "Apache Kafka", ["tp.prices", "tp.reddit", "tp.stocktwits", "tp.news", "key = ticker"], WARN)
    arrow(7.1, 3.8, 8.2, 3.8, "stream")
    box(8.2, 2.7, 2.6, 2.2, "Spark Streaming", ["parse JSON", "validate schema", "idempotent upsert"], ACCENT2)
    arrow(10.8, 3.8, 11.9, 3.8)
    box(11.9, 2.7, 2.9, 2.2, "MongoDB", ["prices / reddit", "stocktwits / news", "unique keys per record"], UP)

    box(6.2, 0.25, 8.6, 1.75, "Analytics layer (Python)",
        ["sentiment scoring  >  daily features  >  walk-forward forecast (Ridge + GradBoost)",
         "analyst note (rule-based or any OpenAI-compatible LLM)  >  webhook / files"], DOWN)
    arrow(13.35, 2.7, 13.35, 2.0, "read")
    fig.text(0.012, 0.012, "Source of truth: docker-compose.yml, tickerpulse/producers, tickerpulse/streaming, tickerpulse/analytics", color=MUTED, fontsize=8)
    fig.savefig(path, dpi=130, bbox_inches="tight", facecolor=BG); plt.close(fig)


# ---------------------------------------------------------------- 2. market overview
def market_overview(path: Path, daily, results):
    tickers = list(results)
    rows = int(np.ceil(len(tickers) / 3))
    fig = plt.figure(figsize=(15, 3.6 * rows + 1.6))
    header(fig, "Market overview", f"{len(tickers)} tickers  |  last close {daily['day'].max():%Y-%m-%d}  |  3-day ensemble forecast with 80% range")
    gs = fig.add_gridspec(rows, 3, left=0.04, right=0.985, top=0.84, bottom=0.08, hspace=0.5, wspace=0.22)
    for k, t in enumerate(tickers):
        ax = fig.add_subplot(gs[k // 3, k % 3])
        res = results[t]
        px = daily[daily["ticker"] == t].sort_values("day").tail(60)
        chg = px["close"].iloc[-1] / px["close"].iloc[-6] - 1
        col = UP if res.forecast.loc[3, "Ensemble"] >= res.last_close else DOWN
        ax.plot(px["day"], px["close"], color=ACCENT, lw=1.8)
        fdays = pd.bdate_range(res.last_day, periods=4)
        fc = [res.last_close, *res.forecast["Ensemble"].tolist()]
        lo = [res.last_close, *res.forecast["low"].tolist()]
        hi = [res.last_close, *res.forecast["high"].tolist()]
        ax.plot(fdays, fc, color=col, lw=2, ls="--", marker="o", ms=3.5)
        ax.fill_between(fdays, lo, hi, color=col, alpha=0.18)
        ax.set_title(f"{t}  ${res.last_close:,.2f}", loc="left", fontsize=12, fontweight="bold")
        exp = res.forecast.loc[3, "Ensemble"] / res.last_close - 1
        ax.text(1.0, 1.04, f"5d {chg:+.1%}", transform=ax.transAxes, ha="right", fontsize=9,
                color=UP if chg >= 0 else DOWN)
        ax.text(0.80, 1.04, f"3d fcst {exp:+.1%}", transform=ax.transAxes, ha="right", fontsize=9, color=col)
        style_dates(ax)
    footer(fig)
    fig.savefig(path, dpi=130, bbox_inches="tight", facecolor=BG); plt.close(fig)


# ---------------------------------------------------------------- 3. sentiment heatmap
def sentiment_heatmap(path: Path, feats):
    days = sorted(feats["day"].unique())[-30:]
    piv = feats[feats["day"].isin(days)].pivot(index="ticker", columns="day", values="sentiment_mean")
    cnt = feats[feats["day"].isin(days)].groupby("ticker")["post_count"].sum().reindex(piv.index)
    fig = plt.figure(figsize=(15, 6.4))
    header(fig, "Crowd sentiment heatmap", "Mean sentiment per ticker per day (last 30 trading days) - Reddit + StockTwits + news")
    gs = fig.add_gridspec(1, 2, width_ratios=[5, 1.1], left=0.07, right=0.97, top=0.82, bottom=0.18, wspace=0.05)
    ax = fig.add_subplot(gs[0])
    im = ax.imshow(piv.values, aspect="auto", cmap="RdYlGn", vmin=-0.6, vmax=0.6)
    ax.set_yticks(range(len(piv))); ax.set_yticklabels(piv.index, fontsize=11, fontweight="bold")
    step = 4
    ax.set_xticks(range(0, len(days), step))
    ax.set_xticklabels([pd.Timestamp(d).strftime("%b %d") for d in days][::step])
    for s in ax.spines.values():
        s.set_visible(False)
    cb = fig.colorbar(im, ax=ax, orientation="horizontal", fraction=0.06, pad=0.18)
    cb.set_label("sentiment (-1 bearish ... +1 bullish)", color=MUTED); cb.ax.tick_params(colors=MUTED)
    ax2 = fig.add_subplot(gs[1])
    ax2.barh(range(len(cnt)), cnt.values, color=ACCENT2)
    ax2.set_yticks([]); ax2.invert_yaxis(); ax2.set_title("posts (30d)", fontsize=10, color=MUTED)
    for i, v in enumerate(cnt.values):
        ax2.text(v, i, f" {int(v):,}", va="center", fontsize=9)
    ax2.set_xlim(0, cnt.max() * 1.3); ax2.grid(False)
    footer(fig)
    fig.savefig(path, dpi=130, bbox_inches="tight", facecolor=BG); plt.close(fig)


# ---------------------------------------------------------------- 4. ticker deep dive
def deep_dive(path: Path, ticker, daily, feats, res):
    px = daily[daily["ticker"] == ticker].sort_values("day").tail(75)
    f = feats[feats["ticker"] == ticker].set_index("day").reindex(px["day"]).ffill()
    fig = plt.figure(figsize=(15, 9.2))
    header(fig, f"{ticker} - {company_name(ticker)}: deep dive",
           "Price, forecast, and the sentiment features that feed the models")
    gs = fig.add_gridspec(4, 1, height_ratios=[2.6, 1.1, 1.1, 1.1], left=0.06, right=0.97, top=0.87,
                          bottom=0.07, hspace=0.35)
    ax = fig.add_subplot(gs[0])
    ax.plot(px["day"], px["close"], color=ACCENT, lw=2, label="close")
    ax.plot(px["day"], px["close"].rolling(10).mean(), color=MUTED, lw=1, ls=":", label="10d mean")
    fdays = pd.bdate_range(res.last_day, periods=4)
    ax.plot(fdays, [res.last_close, *res.forecast["Ensemble"]], color=WARN, lw=2.2, ls="--", marker="o", label="ensemble forecast")
    ax.fill_between(fdays, [res.last_close, *res.forecast["low"]], [res.last_close, *res.forecast["high"]],
                    color=WARN, alpha=0.2, label="80% range")
    ax.legend(loc="upper left", frameon=False, ncol=4); ax.set_ylabel("USD"); style_dates(ax)
    a2 = ax.twinx(); a2.bar(px["day"], px["volume"], color=GRID, alpha=0.5, width=0.8); a2.set_ylim(0, px["volume"].max() * 5)
    a2.set_yticks([]); a2.spines["right"].set_visible(False); ax.set_zorder(a2.get_zorder() + 1); ax.patch.set_visible(False)

    ax = fig.add_subplot(gs[1]); ax.axhline(0, color=GRID)
    ax.plot(f.index, f["sentiment_mean"], color=UP, lw=1.6, label="mean")
    ax.plot(f.index, f["engagement_sentiment"], color=ACCENT2, lw=1.2, label="engagement-weighted")
    ax.fill_between(f.index, f["sentiment_mean"] - f["sentiment_dispersion"] / 2,
                    f["sentiment_mean"] + f["sentiment_dispersion"] / 2, color=UP, alpha=0.1)
    ax.set_ylabel("sentiment"); ax.legend(loc="upper left", frameon=False, ncol=2, fontsize=8); style_dates(ax)

    ax = fig.add_subplot(gs[2])
    ax.plot(f.index, f["fear_score"], color=DOWN, lw=1.6, label="fear score")
    ax.plot(f.index, f["catalyst_buzz"], color=WARN, lw=1.6, label="catalyst buzz")
    ax.set_ylabel("per post"); ax.legend(loc="upper left", frameon=False, ncol=2, fontsize=8); style_dates(ax)

    ax = fig.add_subplot(gs[3])
    ax.bar(f.index, f["attention_surge"], color=[UP if v >= 0 else DOWN for v in f["attention_surge"]], width=0.8)
    ax.set_ylabel("attention surge"); style_dates(ax)
    footer(fig)
    fig.savefig(path, dpi=130, bbox_inches="tight", facecolor=BG); plt.close(fig)


# ---------------------------------------------------------------- 5. model leaderboard
def model_panel(path: Path, results, focus: str):
    names = ["Persistence", "Ridge", "GradBoost", "Ensemble"]
    cols = ["#6b7785", ACCENT, ACCENT2, WARN]
    tick = list(results)
    fig = plt.figure(figsize=(15, 8.4))
    header(fig, "Model evaluation (walk-forward, last 30 days)",
           "Models are refit every 5 days on past data only; persistence = 'tomorrow equals today'")
    gs = fig.add_gridspec(2, 2, left=0.06, right=0.97, top=0.86, bottom=0.08, hspace=0.42, wspace=0.34)

    ax = fig.add_subplot(gs[0, :])
    w = 0.2
    for j, n in enumerate(names):
        vals = [results[t].metrics.loc[n, "MAPE_1d"] for t in tick]
        ax.bar(np.arange(len(tick)) + (j - 1.5) * w, vals, w, color=cols[j], label=n)
    ax.set_xticks(range(len(tick))); ax.set_xticklabels(tick, fontsize=11, fontweight="bold")
    ax.set_ylabel("1-day MAPE (%)  lower is better"); ax.legend(frameon=False, ncol=4, loc="upper right"); ax.grid(True, axis="y")

    r = results[focus]
    ax = fig.add_subplot(gs[1, 0])
    wf = r.walk_forward
    actual = wf["close"] * np.exp(wf["actual"]); pred = wf["close"] * np.exp(wf["Ensemble"])
    ax.plot(wf.index, actual, color=TXT, lw=1.8, label="actual next-day close")
    ax.plot(wf.index, pred, color=WARN, lw=1.6, ls="--", label="ensemble prediction")
    ax.set_title(f"{focus}: predicted vs actual", loc="left", fontsize=11)
    ax.legend(frameon=False, fontsize=8, loc="upper left"); style_dates(ax)

    ax = fig.add_subplot(gs[1, 1])
    imp = r.importances.head(8)[::-1]
    sentiment_cols = {"sentiment_mean", "sentiment_dispersion", "fear_score", "catalyst_buzz",
                      "engagement_sentiment", "bull_ratio", "post_count", "attention_surge"}
    ax.barh(imp.index, imp.values, color=[ACCENT2 if i in sentiment_cols else ACCENT for i in imp.index])
    ax.set_title(f"{focus}: top features (purple = sentiment, blue = technical)", loc="left", fontsize=11)
    ax.grid(True, axis="x")
    footer(fig, "windows are short - treat metrics as illustrative")
    fig.savefig(path, dpi=130, bbox_inches="tight", facecolor=BG); plt.close(fig)


# ---------------------------------------------------------------- 6. terminal-style captures
def terminal(path: Path, title: str, text: str, width=15, size=9.6):
    lines = text.rstrip().split("\n")
    h = max(3.2, 0.215 * len(lines) + 1.1)
    fig = plt.figure(figsize=(width, h)); fig.patch.set_facecolor("#0b0e12")
    ax = fig.add_axes([0, 0, 1, 1]); ax.axis("off"); ax.set_xlim(0, 1); ax.set_ylim(0, 1)
    ax.add_patch(plt.Rectangle((0, 1 - 0.55 / h), 1, 0.55 / h, color="#1c232c"))
    for i, c in enumerate(("#ff5f56", "#ffbd2e", "#27c93f")):
        ax.add_patch(plt.Circle((0.014 + i * 0.016, 1 - 0.27 / h), 0.0045 * 15 / width * 1.6, color=c, transform=ax.transAxes))
    ax.text(0.5, 1 - 0.27 / h, title, ha="center", va="center", color=MUTED, fontsize=10)
    for i, ln in enumerate(lines):
        y = 1 - (0.8 + i * 0.215) / h
        color = TXT
        if ln.startswith("$"): color = UP
        elif ln.strip().startswith(("OUTLOOK", "CONVICTION")) : color = WARN
        elif ln.isupper() and ln.strip(): color = ACCENT
        elif ln.startswith("wrote"): color = ACCENT
        ax.text(0.015, y, ln, family="DejaVu Sans Mono", fontsize=size, color=color, va="center")
    fig.savefig(path, dpi=130, facecolor="#0b0e12"); plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/screenshots")
    ap.add_argument("--tickers", nargs="*", default=["NVDA", "TSLA", "GOOGL", "AAPL", "MSFT", "AMZN"])
    ap.add_argument("--focus", default="TSLA")
    a = ap.parse_args()
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)

    prices, reddit, st, news = generate(a.tickers)
    daily, feats, results, notes = analyze(prices, reddit, st, news, a.tickers)

    architecture(out / "01_architecture.png")
    market_overview(out / "02_market_overview.png", daily, results)
    sentiment_heatmap(out / "03_sentiment_heatmap.png", feats)
    deep_dive(out / "04_ticker_deep_dive.png", a.focus, daily, feats, results[a.focus])
    model_panel(out / "05_model_evaluation.png", results, a.focus)
    terminal(out / "06_analyst_note.png", f"reports/{a.focus}.txt", notes[a.focus])

    run_log = "\n".join([
        "$ python -m tickerpulse.analytics.pipeline --demo --tickers " + " ".join(a.tickers),
        *[f"wrote reports/{t}_<timestamp>.txt   outlook={notes[t].split('OUTLOOK: ')[1].split(chr(10))[0]:<8} "
          f"3d forecast {results[t].forecast.loc[3, 'Ensemble'] / results[t].last_close - 1:+.2%}" for t in results],
    ])
    terminal(out / "07_cli_run.png", "terminal", run_log, size=9.2)
    print("screenshots written to", out)


if __name__ == "__main__":
    main()
